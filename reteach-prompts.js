    '部分與總量': '你會用哪一部分作未知數？其餘各部分怎樣用它表示，再相加成總量？',
    '固定與變動量': '把金額分成固定的一筆和按數量計算的一筆。你會怎樣用這兩筆錢列式？',
    '比例轉換': '先用同一個未知數表示原來兩組的數量。改動後，每組的算式分別變成甚麼？',
    '追及問題': '請畫出起步時兩者的位置。每分鐘縮短多少距離，才能把原有的差距補上？',
    '解的情況': '把等式兩邊展開。如果要對每一個未知數的值都成立，哪些係數和常數必須相同？',
    '百分率基數': '題中哪個數量代表 100%？請用「部分 ÷ 整體」列式，再把結果寫成百分率。',
    '逆百分法': '先把原量當作 100%。變動後的量是原量的幾倍？已知變動後的量，怎樣倒推原量？',
    '連續變化': '先把原量設為 100。第一次變化後剩多少？第二次的百分率要乘在哪個數上？',
    '折扣次序': '完成第一項優惠後，價錢是多少？第二項優惠應該用哪個金額計算？',
    '成本與盈利': '先列出成本、售價和兩者的差額。題目問的百分比應該用哪一個金額做分母？',
    '目標標價': '由成本和目標利潤先算出實收金額。知道折扣後，怎樣倒推標價？',
    '百分點': '把前後兩個百分率相減，得到多少個百分點？若要計相對變幅，差額要除以哪個基數？',
    '加權比率': '各組的百分率分別代表多少人或物件？把各組數量合起來後，整體比率的分母是多少？',
    '單利': '利率以一年計，題目的月數相當於多少年？把本金、年利率和時間代入後，還要求哪一項？',
    '比較方案': '分別算出兩個方案的實付金額。應拿哪兩個數相減，才是實際節省的金額？',
    '損益平衡': '每賣一件扣除成本和費用後，還剩多少可抵銷固定開支？你怎樣判斷件數足夠？',
    '提出假設': '實驗開始前，你預測哪一組的讀數較高？量度甚麼就能檢查你的預測？',
    '變量辨認': '實驗者刻意改變的是甚麼？用來比較結果的量又是甚麼？',
