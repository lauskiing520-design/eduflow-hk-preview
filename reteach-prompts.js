    '量度安排': '兩組的儀器應分別放在哪裏？請說出一項要保持相同的安排，以及它怎樣影響讀數。',
    '讀取曲線': '先在橫軸找到題目指定的位置。沿兩條曲線讀出縱軸數值後，怎樣算出兩者的差？',
    '計算變化': '先寫下起始和結束的讀數。題目問的是增加還是下降了多少？你會用哪個讀數減哪個？',
